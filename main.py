@app.post("/api/admin/offices/{office_id}/subscription")
async def admin_manage_subscription(
    office_id: str,
    action_req: AdminSubscriptionAction,
    x_office_token: Optional[str] = Header(None),
    authorization: Optional[str] = Header(None)
):
    caller = resolve_office(x_office_token, authorization)
    if not (caller.get("is_admin") or caller.get("role") == "super_admin" or caller.get("id") == "office_super_admin"):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="صلاحية مرفوضة: لا تملك صلاحية تعديل اشتراكات مكاتب المحاماة."
        )

    if office_id not in OFFICES:
        raise HTTPException(status_code=404, detail="المكتب غير موجود")
    target = OFFICES[office_id]
    now = datetime.now()
    cur_end = datetime.fromisoformat(target["trial_end"])
    base_time = max(now, cur_end)

    if action_req.action == "extend_15":
        target["trial_end"] = (base_time + timedelta(days=15)).isoformat()
        target["is_active"] = True
        target["plan"] = "trial_15"
    elif action_req.action == "extend_30":
        target["trial_end"] = (base_time + timedelta(days=30)).isoformat()
        target["is_active"] = True
        target["plan"] = "trial_extended"
    elif action_req.action == "upgrade_pro":
        target["trial_end"] = (now + timedelta(days=365)).isoformat()
        target["is_active"] = True
        target["plan"] = "pro_annual"
    elif action_req.action == "toggle_status":
        target["is_active"] = not target.get("is_active", True)
    elif action_req.action == "expire_now":
        target["trial_end"] = (now - timedelta(hours=1)).isoformat()
        target["is_active"] = False
        target["plan"] = "expired"

    tend = datetime.fromisoformat(target["trial_end"])
    return {
        "status": "success",
        "message": f"تم تحديث اشتراك {target['name']} بنجاح",
        "office": {
            "id": target["id"],
            "name": target["name"],
            "is_active": target["is_active"],
            "plan": target["plan"],
            "trial_end": target["trial_end"],
            "days_remaining": max(0, (tend - now).days),
            "is_expired": now > tend
        }
    }

