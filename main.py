@app.post("/api/calculators/inheritance")
async def calculate_inheritance(payload: InheritanceCalcRequest):
    shares = []
    total_val = payload.estate_value
    has_children = (payload.sons_count + payload.daughters_count) > 0

    # نصيب الزوج أو الزوجة
    if payload.has_husband:
        husband_share_frac = "1/4" if has_children else "1/2"
        husband_amount = total_val * (0.25 if has_children else 0.5)
        shares.append({
            "heir": "الزوج",
            "fraction": husband_share_frac,
            "amount": round(husband_amount, 2),
            "reason": "لوجود فرع وارث" if has_children else "لعدم وجود فرع وارث"
        })
    elif payload.has_wife:
        wife_share_frac = "1/8" if has_children else "1/4"
        wife_amount = total_val * (0.125 if has_children else 0.25)
        per_wife = wife_amount / max(1, payload.wife_count)
        shares.append({
            "heir": f"الزوجات (العدد: {payload.wife_count})",
            "fraction": wife_share_frac,
            "amount": round(wife_amount, 2),
            "per_person": round(per_wife, 2),
            "reason": "لوجود فرع وارث يقسم بينهن بالتساوي" if has_children else "لعدم وجود فرع وارث"
        })

    # نصيب الأب والأم
    if payload.has_mother:
        mother_frac = "1/6" if has_children else "1/3"
        mother_amt = total_val * (1/6 if has_children else 1/3)
        shares.append({
            "heir": "الأم",
            "fraction": mother_frac,
            "amount": round(mother_amt, 2),
            "reason": "السدس فرضاً لوجود فرع وارث" if has_children else "الثلث فرضاً لعدم الفرع الوارث"
        })

    if payload.has_father:
        father_amt = total_val * (1/6)
        shares.append({
            "heir": "الأب",
            "fraction": "1/6 فرضاً + الباقي تعصيباً إن وجد",
            "amount": round(father_amt, 2),
            "reason": "السدس فرضاً مع وجود فرع وارث مذكر"
        })

    # الأولاد (عصبة بالغير للذكر مثل حظ الأنثيين)
    allocated = sum(s["amount"] for s in shares)
    remainder = max(0.0, total_val - allocated)
    total_portions = (payload.sons_count * 2) + payload.daughters_count

    if total_portions > 0 and remainder > 0:
        portion_value = remainder / total_portions
        if payload.sons_count > 0:
            son_single = portion_value * 2
            shares.append({
                "heir": f"الأبناء الذكور (العدد: {payload.sons_count})",
                "fraction": "عصبة بالغير (سهمين لكل ابن)",
                "amount": round(son_single * payload.sons_count, 2),
                "per_person": round(son_single, 2),
                "reason": "للذكر مثل حظ الأنثيين مما تبقّى بعد أصحاب الفروض"
            })
        if payload.daughters_count > 0:
            shares.append({
                "heir": f"البنات الإناث (العدد: {payload.daughters_count})",
                "fraction": "عصبة بالغير (سهم لكل بنت)",
                "amount": round(portion_value * payload.daughters_count, 2),
                "per_person": round(portion_value, 2),
                "reason": "تعصيباً بالغير مع الإخوة الذكور"
            })

    return {
        "status": "success",
        "estate_value": total_val,
        "shares": shares,
        "legal_basis": "قانون المواريث المصري رقم 77 لسنة 1943 وأحكام الشريعة الإسلامية"
    }

